    // Outbound & Picking List Sync
    function syncPickingListToSuratJalan() {
        const checkboxes = document.querySelectorAll('.pick-item');
        const tableBody = document.getElementById('suratJalanTableBody');
        let selectedCount = 0;
        let html = '';

        checkboxes.forEach(cb => {
            if (cb.checked) {
                selectedCount++;
                const row = cb.closest('.picking-row');
                const name = cb.dataset.name;
                const qtyInput = row ? row.querySelector('.pick-qty') : null;
                const qty = qtyInput ? qtyInput.value : (cb.dataset.qty || 1);
                const date = cb.dataset.date || new Date().toLocaleDateString('id-ID');
                html += `
                    <tr>
                        <td class="fw-bold">${name}</td>
                        <td class="text-center fw-800">x${qty}</td>
                        <td class="text-right">${date}</td>
                    </tr>
                `;
            }
        });

        if (html === '') {
            html = `<tr><td colspan="3" class="text-center text-slate-400">Belum ada item dipilih</td></tr>`;
        }
        
        if (tableBody) tableBody.innerHTML = html;
        const countSpan = document.getElementById('pickingSelectedCount');
        if (countSpan) countSpan.innerText = `${selectedCount} Selected Items`;
    }

