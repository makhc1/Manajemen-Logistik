    function renderWarehouses() {
        const whs = getWarehouses();
        
        // 1. Render Header Dropdown
        const whSelector = document.getElementById('warehouseSelector');
        if (whSelector) {
            const currentValue = whSelector.value;
            whSelector.innerHTML = whs.map(w => `<option value="${w.name}">${w.name}</option>`).join('');
            if (whs.find(w => w.name === currentValue)) {
                whSelector.value = currentValue;
            }
        }
        
        // 2. Render Warehouse Grid
        const whGrid = document.getElementById('warehouseGrid');
        if (whGrid) {
            whGrid.innerHTML = whs.map(w => {
                let badgeColor = '#E85A1C'; // AKTIF
                if (w.status === 'OPERASIONAL') badgeColor = '#10B981';
                else if (w.status === 'TRANSIT') badgeColor = '#2563EB';
                
                return `
                    <div class="wh-card">
                        <h4 class="wh-title">${w.name}</h4>
                        <p class="wh-capacity">Kapasitas: ${w.percentage}% (${w.capacity_used.toLocaleString()} / ${w.capacity.toLocaleString()} unit)</p>
                        <span class="wh-badge" style="background: ${badgeColor};">${w.status}</span>
                        
                        <div class="wh-actions">
                            <button class="btn-wh-edit" data-id="${w.id}"><i class="fa-solid fa-pen"></i></button>
                            <button class="btn-wh-delete" data-id="${w.id}"><i class="fa-solid fa-trash"></i></button>
                        </div>
                    </div>
                `;
            }).join('');
        }
    }

