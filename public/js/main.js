    async function saveWarehouse(e) {
        e.preventDefault();
        const id = document.getElementById('whId').value;
        const data = {
            name: document.getElementById('whName').value,
            capacity: parseInt(document.getElementById('whCapacity').value),
            status: document.getElementById('whStatus').value
        };
        
        try {
            const url = id ? '/api/warehouses/' + id : '/api/warehouses';
            const method = id ? 'PUT' : 'POST';
            
            const res = await fetch(url, {
                method: method,
                headers: {'Content-Type': 'application/json', 'Accept': 'application/json'},
                body: JSON.stringify(data)
            });
            const result = await res.json();
            if(result.success) {
                closeModal('whModal');
                showToast(id ? 'Gudang diperbarui!' : 'Gudang ditambahkan!');
                fetchWarehouses();
                // If a warehouse name changed, products might have updated location
                if (id) fetchProducts();
            }
        } catch (err) {
            showToast('Gagal menyimpan gudang');
        }
    }
    
    async function deleteWarehouse(id) {
        if(confirm('Yakin ingin menghapus gudang ini?')) {
            try {
                const res = await fetch('/api/warehouses/' + id, { method: 'DELETE' });
                const data = await res.json();
                if(data.success) {
                    showToast('Gudang dihapus!');
                    fetchWarehouses();
                }
            } catch(e) {
                showToast('Gagal menghapus gudang');
            }
        }
    }

    function showToast(message) {
        const toast = document.getElementById('toast');
        if (!toast) return;
        document.getElementById('toastMessage').innerText = message;
        toast.classList.add('show');
        setTimeout(() => {
            toast.classList.remove('show');
        }, 3200);
    }

